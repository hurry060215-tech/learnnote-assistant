/** Actual importer; all API bytes and vault actions are local fixtures. */
import assert from "node:assert/strict";
import fs from "node:fs/promises";
import path from "node:path";
import { createRequire } from "node:module";
import { pathToFileURL, fileURLToPath } from "node:url";
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"..");
const option=(name,fallback="")=>{const i=process.argv.indexOf(name);return i<0?fallback:process.argv[i+1];};
const fixturePath=path.resolve(option("--fixture"));
const fixture=JSON.parse(await fs.readFile(fixturePath,"utf8"));
const bundle=await fs.readFile(path.resolve(path.dirname(fixturePath),fixture.bundle));
const output=path.resolve(option("--output",path.join(root,"build/obsidian-unicode")));
await fs.mkdir(output,{recursive:true});
const require=createRequire(path.join(root,"integrations/obsidian-learnnote/package.json"));
const {build}=require("esbuild");
const modulePath=path.join(output,"importer-fixture.mjs");
await build({stdin:{contents:`export {LearnNoteImporter} from ${JSON.stringify(path.join(root,"integrations/obsidian-learnnote/src/importer.ts"))}; export {taskFolderCandidates} from ${JSON.stringify(path.join(root,"integrations/obsidian-learnnote/src/core.mjs"))}; export {TFile,TFolder} from "obsidian";`,resolveDir:root,loader:"ts"},outfile:modulePath,bundle:true,platform:"node",format:"esm",nodePaths:[path.join(root,"integrations/obsidian-learnnote/node_modules")],plugins:[{name:"memory-vault",setup(b){b.onResolve({filter:/^obsidian$/},()=>({path:"obsidian",namespace:"fixture"}));b.onLoad({filter:/.*/,namespace:"fixture"},()=>({contents:`export class TFile{constructor(path,content=""){this.path=path;this.content=content;}} export class TFolder{constructor(path){this.path=path;}} export const normalizePath=value=>String(value).replace(/\\\\/g,"/").replace(/\\/{2,}/g,"/");`,loader:"js"}));}}]});
const {LearnNoteImporter,TFile,TFolder,taskFolderCandidates}=await import(pathToFileURL(modulePath));
const files=new Map();
const app={vault:{getAbstractFileByPath:p=>files.get(p),createFolder:async p=>{const f=new TFolder(p);files.set(p,f);return f;},create:async(p,c)=>{const f=new TFile(p,c);files.set(p,f);return f;},modify:async(f,c)=>{f.content=c;},createBinary:async(p,c)=>{const f=new TFile(p,c);files.set(p,f);return f;},modifyBinary:async(f,c)=>{f.content=c;},read:async f=>f.content},workspace:{getLeaf:()=>({openFile:async()=>{}})}};
const settings={targetFolder:"本地验收",includeManifest:true,includeTranscript:true,includeVisualWindows:true,includeQaHistory:true,openAfterImport:false};
const importer=new LearnNoteImporter(app,{bundle:async()=>Uint8Array.from(bundle).buffer},()=>settings);
const first=await importer.importTask(fixture.task),note=files.get(first.notePath);
assert.ok(note.content.includes(fixture.expected_text));
assert.ok(first.notePath.includes(fixture.task.title));
assert.ok(!note.content.includes("\ufffd"));
assert.ok(files.get(`${first.folderPath}/Transcript.md`).content.includes(fixture.expected_text));
const claimMap=JSON.parse(files.get(`${first.folderPath}/claim_evidence_map.json`).content);
assert.equal(claimMap.claims[0].claim_id,fixture.claim_id);
const personal="个人批注：日本語 café 🧭，保持原样。";
await app.vault.modify(note,note.content+personal);
const second=await importer.importTask(fixture.task);
assert.equal(second.created,false);assert.ok(note.content.includes(personal));assert.ok(note.content.includes(fixture.expected_text));
const legacyTask={...fixture.task,id:"legacy",title:"cafe\u0301"};
const candidates=taskFolderCandidates(settings.targetFolder,legacyTask.title,legacyTask.id);
files.set(`${candidates[1]}/LearnNote.md`,new TFile(`${candidates[1]}/LearnNote.md`,"## 我的补充\n旧路径个人内容"));
const legacy=await importer.importTask(legacyTask);
assert.equal(legacy.folderPath,candidates[1]);
assert.ok(files.get(legacy.notePath).content.includes("旧路径个人内容"));
const report={status:"pass",actual_importer:true,in_memory_vault:true,network_called:false,harness_modifies_plugin:false,checks:10,extracted_files:first.extractedFiles};
await fs.writeFile(path.join(output,"report.json"),JSON.stringify(report,null,2));console.log(JSON.stringify(report));
