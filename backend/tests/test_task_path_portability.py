class TaskPathPortabilityTests(unittest.TestCase):
    def setUp(self):
        self.stack = ExitStack()
        self.addCleanup(self.stack.close)
        self.sandbox = Path(self.stack.enter_context(tempfile.TemporaryDirectory()))
        self.tasks = self.sandbox / "selected" / "tasks"
        self.tasks.mkdir(parents=True)
        self.stack.enter_context(patch.object(storage, "TASK_DIR", self.tasks))
        self.stack.enter_context(patch.object(storage, "ensure_dirs", return_value=None))
        self.stack.enter_context(patch.object(library, "TASK_DIR", self.tasks))
        self.stack.enter_context(patch.object(library, "DATA_DIR", self.tasks.parent))
        self.stack.enter_context(patch.object(library, "ensure_dirs", return_value=None))
        self.stack.enter_context(patch("app.routers.notes.DATA_DIR", self.tasks.parent))
        self.client = TestClient(main.app, raise_server_exceptions=False)

    def copied_foreign(self, task_id="a123456789bc"):
        # Build a complete independent fixture, not an output generated by the
        # resolver being tested. The original Windows tree is unavailable here.
        root = self.tasks / task_id
        root.mkdir()
        (root / "note.md").write_bytes("# Copied lesson\n\n字幕原文与自己的理解。\n".encode())
        transcript = {"source": "browser-subtitle", "full_text": "A copied caption.", "segments": [{"start": 0, "end": 5, "text": "A copied caption."}]}
        (root / "transcript.json").write_text(json.dumps(transcript), encoding="utf-8")
        (root / "browser_subtitles.srt").write_text("1\n00:00:00,000 --> 00:00:05,000\nA copied caption.\n", encoding="utf-8")
        (root / "visual_index.json").write_text('{"windows":[]}', encoding="utf-8")
        (root / "grids").mkdir()
        (root / "grids" / "grid_001.jpg").write_bytes(b"synthetic image")
        old = ("/previous/learnnote/data/tasks/" + task_id + "/") if os.name == "nt" else ("D:\\LearnNote\\data\\tasks\\" + task_id + "\\")
        task = TaskRecord(id=task_id, source_type="local", title="Copied lesson", status="success", created_at="2026-10-16", updated_at="2026-10-16",
                          note_path=old + "note.md", transcript_path=old + "transcript.json", subtitle_path=old + "browser_subtitles.srt", visual_index_path=old + "visual_index.json")
        # Deliberately retain unknown legacy data and noncanonical whitespace.
        (root / "task.json").write_text(json.dumps({**task.model_dump(mode="json"), "legacy_fixture": {"keep": "verbatim"}}, indent=4) + "\n", encoding="utf-8")
        return root, task

    def hashes(self, root):
        return {str(p.relative_to(root)): hashlib.sha256(p.read_bytes()).hexdigest() for p in root.rglob("*") if p.is_file()}

    def test_copied_windows_reads_real_api_exports_index_and_snapshot_without_rewriting(self):
        root, task = self.copied_foreign()
        before = self.hashes(root)
        self.assertIn("Copied lesson", task_artifacts.read_task_note(task.id))
        self.assertEqual(task_artifacts.read_task_transcript(task.id)["full_text"], "A copied caption.")
        self.assertEqual(processor.read_note(task.id), (root / "note.md").read_text())
        self.assertEqual(processor.read_transcript(task.id)["full_text"], "A copied caption.")
        self.assertEqual(processor.read_visual_index(task.id), {"windows": []})
        self.assertEqual(owned_caption_path(task), root / "transcript.json")
        self.assertEqual(summary_versions._owned_note(task.id), root / "note.md")
        self.assertEqual(task_artifacts.owned_task_artifact(task.id, task.note_path), root / "note.md")
        self.assertEqual(task_artifacts.owned_task_artifact(task.id, task.note_path[:-len("note.md")] + ("grids\\grid_001.jpg" if "\\" in task.note_path else "grids/grid_001.jpg"), directory="grids"), root / "grids" / "grid_001.jpg")
        for endpoint in ("note", "transcript", "exports/markdown", "exports/subtitles", "exports/sanitized-bundle"):
            result = self.client.get(f"/api/tasks/{task.id}/{endpoint}")
            self.assertEqual(result.status_code, 200, (endpoint, result.text))
            if endpoint == "exports/sanitized-bundle":
                with ZipFile(BytesIO(result.content)) as archive:
                    self.assertIn(b"Copied lesson", archive.read("note.md"))
                    self.assertEqual(json.loads(archive.read("transcript.json"))["full_text"], "A copied caption.")
        edition = self.client.get(f"/api/tasks/editions/task/{task.id}")
        self.assertEqual(edition.status_code, 200, edition.text)
        self.assertIn("Copied lesson", edition.json()["text"])
        status = main.task_artifact_status(task)
        self.assertTrue(status["note_ready"])
        self.assertTrue(status["transcript_ready"])
        self.assertEqual(status["path_diagnostics"], {})
        self.assertTrue(library.index_task(task))
        connection, _ = library._connect()
        try:
            content = connection.execute("SELECT content FROM library_tasks WHERE task_id=?", (task.id,)).fetchone()[0]
            self.assertIn("A copied caption.", content)
            self.assertIn("自己的理解", content)
        finally:
            connection.close()
        self.assertEqual(self.hashes(root), before)
        self.assertEqual(storage.get_task(task.id).note_path, task.note_path)

    def test_save_passes_selected_storage_root_to_index_callback(self):
        root, task = self.copied_foreign()
        with patch.object(storage, "index_task", return_value=True) as index:
            storage.save_task(task)
        index.assert_called_once_with(task, task_root=root)

    def test_copied_posix_outside_path_requires_preview_without_probing_old_location(self):
        root, task = self.copied_foreign()
        old = self.sandbox / "original" / "tasks" / task.id
        old.mkdir(parents=True)
        (old / "note.md").write_bytes(b"different original")
        # Both copies exist. The same result is required when the source is gone:
        # deciding existence would itself probe a manifest-selected outside path.
        real_lstat = Path.lstat
        def guarded_lstat(path, *args, **kwargs):
            if path == old or old in path.parents:
                raise AssertionError("Never inspect the outside original")
            return real_lstat(path, *args, **kwargs)
        for present in (True, False):
            if not present:
                (old / "note.md").unlink()
            with self.subTest(original_exists=present), patch.object(Path, "lstat", guarded_lstat):
                with self.assertRaisesRegex(TaskArtifactUnavailable, "迁移映射") as result:
                    resolve_task_artifact(root, task.id, str(old / "note.md"), field="note_path")
                self.assertEqual(result.exception.reason, "native_mapping_requires_preview")
        # Explicit task-relative metadata already selects one owned destination.
        payload = json.loads((root / "task.json").read_text())
        payload["note_path"] = "note.md"
        (root / "task.json").write_text(json.dumps(payload), encoding="utf-8")
        before = self.hashes(root)
        self.assertEqual(task_artifacts.read_task_note(task.id), (root / "note.md").read_text())
        self.assertEqual(self.hashes(root), before)

    def test_native_owned_path_and_empty_optional_artifacts_preserve_behavior(self):
        root, task = self.copied_foreign()
        task.note_path = str(root / "note.md")
        self.assertEqual(task_artifacts.task_artifact_path(task, "note_path"), root / "note.md")
        task.note_path = ""
        self.assertIsNone(task_artifacts.task_artifact_path(task, "note_path"))
        self.assertIsNone(resolve_task_artifact(root, task.id, "", field="transcript_path"))

    def test_rejects_unowned_ambiguous_traversal_network_and_external_media_paths(self):
        root, task = self.copied_foreign()
        before = self.hashes(root)
        paths = [
            r"D:\LearnNote\data\tasks\other\note.md",
            r"D:\LearnNote\data\tasks\a123456789bc\..\a123456789bc\note.md",
            r"D:\tasks\a123456789bc\tasks\a123456789bc\note.md",
            r"D:tasks\a123456789bc\note.md",
            r"\\server\share\tasks\a123456789bc\note.md",
            r"\\?\D:\tasks\a123456789bc\note.md",
            r"D:\tasks\a123456789bc\note.md:stream",
            r"D:\tasks/a123456789bc/note.md",
            "../note.md", "https://example.invalid/tasks/a123456789bc/note.md",
            r"D:\uploads\note.md", r"D:\tasks\a123456789bc\custom-note.md",
            r"D:\tasks\a123456789bc\nested\note.md",
        ]
        for value in paths:
            with self.subTest(path=value), self.assertRaises(TaskArtifactUnavailable):
                resolve_task_artifact(root, task.id, value, field="note_path")
        for task_id in ("..", "../a123456789bc", "", "bad/id", "a" * 129):
            with self.subTest(task_id=task_id), self.assertRaises(TaskArtifactUnavailable):
                resolve_task_artifact(root, task_id, task.note_path, field="note_path")
        with self.assertRaises(TaskArtifactUnavailable):
            resolve_task_artifact(root, task.id, r"D:\tasks\a123456789bc\media.mp4", field="source_media_path")
        self.assertEqual(self.hashes(root), before)

    def test_missing_directory_file_type_and_identity_fail_with_visible_recovery(self):
        root, task = self.copied_foreign()
        (root / "note.md").unlink()
        for directory in (False, True):
            if directory:
                (root / "note.md").mkdir()
            result = self.client.get(f"/api/tasks/{task.id}/note")
            self.assertEqual(result.status_code, 409, result.text)
            detail = result.json()["detail"]
            self.assertEqual(detail["code"], "task_artifact_unavailable")
            self.assertTrue(detail["requires_preview"])
            self.assertIn("迁移映射", detail["message"])
            edition = self.client.get(f"/api/tasks/editions/task/{task.id}")
            self.assertEqual(edition.status_code, 409, edition.text)
            self.assertTrue(edition.json()["detail"]["requires_preview"])
            self.assertFalse(main.task_artifact_status(task)["note_ready"])
            self.assertIn("note_path", main.task_artifact_status(task)["path_diagnostics"])
        (root / "note.md").rmdir()
        (root / "note.md").write_bytes(b"owned")
        payload = json.loads((root / "task.json").read_text()); payload["id"] = "other"
        (root / "task.json").write_text(json.dumps(payload))
        result = self.client.get(f"/api/tasks/{task.id}/note")
        self.assertEqual(result.status_code, 409, result.text)
        self.assertEqual(result.json()["detail"]["reason"], "task_identity_mismatch")

    def test_final_file_grid_ancestor_task_root_and_tasks_root_symlinks_are_rejected(self):
        root, task = self.copied_foreign()
        outside = self.sandbox / "outside"; outside.mkdir()
        (outside / "note.md").write_bytes(b"outside secret fixture")
        for target, link_to in ((root / "note.md", outside / "note.md"), (root / "grids", outside), (root, outside), (self.tasks, outside)):
            with self.subTest(target=target.name):
                backup = target.with_name(target.name + "-saved")
                target.rename(backup)
                try:
                    target.symlink_to(link_to, target_is_directory=link_to.is_dir())
                    value = task.note_path if target.name != "grids" else task.note_path[:-len("note.md")] + ("grids\\grid_001.jpg" if "\\" in task.note_path else "grids/grid_001.jpg")
                    with self.assertRaises(TaskArtifactUnavailable):
                        resolve_task_artifact(root, task.id, value, directory="grids" if target.name == "grids" else "")
                except (OSError, NotImplementedError) as exc:
                    self.skipTest(f"Symlink creation unsupported: {exc}")
                finally:
                    if target.is_symlink(): target.unlink()
                    backup.rename(target)
        self.assertEqual((outside / "note.md").read_bytes(), b"outside secret fixture")

    def test_linked_manifest_and_reparse_directory_are_rejected_before_reading(self):
        root, task = self.copied_foreign()
        manifest = root / "task.json"
        original = manifest.read_bytes()
        outside = self.sandbox / "outside-task.json"
        outside.write_bytes(original)
        manifest.unlink()
        try:
            manifest.symlink_to(outside)
        except (OSError, NotImplementedError) as exc:
            manifest.write_bytes(original)
            self.skipTest(f"Symlink creation unsupported: {exc}")
        try:
            result = self.client.get(f"/api/tasks/{task.id}/note")
            self.assertEqual(result.status_code, 409, result.text)
            self.assertEqual(result.json()["detail"]["reason"], "linked_destination")
        finally:
            manifest.unlink(); manifest.write_bytes(original)
        original_lstat = Path.lstat
        def reparse_lstat(path, *args, **kwargs):
            if path == root:
                return SimpleNamespace(st_mode=stat.S_IFDIR, st_file_attributes=0x400)
            return original_lstat(path, *args, **kwargs)
        with patch.object(Path, "lstat", reparse_lstat), self.assertRaises(TaskArtifactUnavailable) as result:
            resolve_task_artifact(root, task.id, task.note_path, field="note_path")
        self.assertEqual(result.exception.reason, "linked_destination")
        self.assertEqual(outside.read_bytes(), original)

    def test_mixed_valid_invalid_and_linked_manifests_do_not_break_task_listing(self):
        root, task = self.copied_foreign()
        before = self.hashes(root)
        invalid = self.tasks / "invalid-task"; invalid.mkdir()
        invalid_manifest = invalid / "task.json"
        payload = task.model_dump(mode="json"); payload["id"] = "different-task"
        invalid_manifest.write_text(json.dumps(payload), encoding="utf-8")
        self.assertEqual([item.id for item in storage.list_tasks_snapshot()], [task.id])
        with self.assertRaisesRegex(ValueError, "course_episode_identity_conflict"):
            storage.list_tasks_snapshot(strict=True)
        response = self.client.get("/api/tasks")
        self.assertEqual(response.status_code, 200, response.text)
        self.assertEqual([item["id"] for item in response.json()["tasks"]], [task.id])
        outside = self.sandbox / "outside-manifest.json"
        outside.write_bytes(invalid_manifest.read_bytes())
        invalid_manifest.unlink()
        try:
            invalid_manifest.symlink_to(outside)
        except (OSError, NotImplementedError) as exc:
            self.skipTest(f"Symlink creation unsupported: {exc}")
        read_text = Path.read_text
        def guarded_read(path, *args, **kwargs):
            if path in (outside, invalid_manifest):
                raise AssertionError("Linked manifests must not be read before skipping")
            return read_text(path, *args, **kwargs)
        with patch.object(Path, "read_text", guarded_read):
            self.assertEqual([item.id for item in storage.list_tasks_snapshot()], [task.id])
            self.assertEqual([item.id for item in storage.list_tasks()], [task.id])
            with self.assertRaises(TaskArtifactUnavailable):
                storage.list_tasks_snapshot(strict=True)
            response = self.client.get("/api/tasks")
            self.assertEqual(response.status_code, 200, response.text)
            self.assertEqual([item["id"] for item in response.json()["tasks"]], [task.id])
        self.assertEqual(self.hashes(root), before)

    def test_known_download_subtitle_directory_is_owned_without_widening_other_fields(self):
        root, task = self.copied_foreign()
        downloads = root / "downloads"; downloads.mkdir()
        subtitle = downloads / "lesson.vtt"; subtitle.write_bytes(b"WEBVTT\n")
